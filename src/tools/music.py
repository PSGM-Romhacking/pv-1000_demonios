#!/usr/bin/env python3
"""The game's music as notes, converted for the PV-1000: src/rom/generated/music.asm.

The PV-1000 sound has 3 square-wave channels, with frequency = 8739 Hz / (63 - n),
n from 0 to 62 (63 = mute). From low to high, the available notes get further and further
apart: up to A4 the tuning is good; above that the notes come out off-pitch. The lowest
note is C#3 (138.7 Hz). That is why the music stays between C#3 and A4.

Channel 1 is kept for the interface beeps; the music uses channels 2 and 3.

Notation: "NOTE:DURATION" separated by spaces; duration in sixteenth notes (BEAT/4
frames each); "-" is a rest; "|" is just for reading. Every note gets a 2-frame breath
at the end, so repeated notes do not run together.

Each piece has a transposition (in semitones), chosen so the notes land close to the
ones the console can play: written in A minor, for example, they come out in C minor.

ROM format, per channel: pairs (n, frames); n = 0xFE loops back to the start; 0xFF ends.

Usage:  python3 src/tools/music.py        (writes src/rom/generated/music.asm and shows the tuning)
"""
import math
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
BASE = 8739.0
SIXTEENTH = 9                   # frames per sixteenth note (quarter note = 36 frames, 100 bpm)
NOTES = {"C": 0, "C#": 1, "D": 2, "D#": 3, "E": 4, "F": 5, "F#": 6, "G": 7, "G#": 8,
         "A": 9, "A#": 10, "B": 11}

# title: a lament written in A minor (played 3 semitones up), looping
TRANSPOSE = {"title": 3, "good": -1, "normal": -2, "bad": 3, "true": -1}
TITLE = (
    "E4:4 D4:2 C4:2 B3:4 A3:4 | C4:4 B3:2 A3:2 G#3:4 E3:4 | "
    "A3:4 C4:2 E4:2 F4:4 E4:4 | D4:2 C4:2 B3:2 G#3:2 A3:8 -:8",
    "A3:16 | E3:8 G#3:8 | F3:16 | E3:8 A3:8 -:8",
)
# ending screens, by ending type: played once
ENDINGS = {
    "good": ("D4:4 F#4:4 A4:4 G4:4 F#4:4 E4:4 D4:16",
             "D3:12 G3:12 D3:16"),
    "normal": ("A3:4 C4:4 E4:4 D4:4 B3:4 C4:12",
               "F3:12 G3:12 E3:12"),
    "bad": ("E4:3 D4:3 C4:3 B3:3 A3:3 G#3:3 E3:12",
            "A3:12 D3:6 C#3:12"),
    "true": ("A3:4 B3:4 C4:4 E4:4 A4:8 G#4:4 A4:16",
             "E3:16 F3:8 E3:4 A3:16"),
}


def freq(name):
    m = re.fullmatch(r"([A-G]#?)(\d)", name)
    semitones = NOTES[m.group(1)] + 12 * (int(m.group(2)) + 1) - 69    # relative to A4
    return 440.0 * 2 ** (semitones / 12)


def transpose(name, k):
    m = re.fullmatch(r"([A-G]#?)(\d)", name)
    i = NOTES[m.group(1)] + 12 * int(m.group(2)) + k
    return list(NOTES)[i % 12] + str(i // 12)


def note_n(name):
    """The PV-1000 n closest to the note, and the deviation in cents."""
    f = freq(name)
    best = min(range(63), key=lambda n: abs(math.log(BASE / (63 - n) / f)))
    cents = 1200 * math.log2(BASE / (63 - best) / f)
    return best, cents


def channel(text, loop, deviations, k):
    out = []
    for item in text.replace("|", " ").split():
        note, dur = item.split(":")
        q = int(dur) * SIXTEENTH
        if note == "-":
            out += [63, q]
            continue
        note = transpose(note, k)
        n, c = note_n(note)
        deviations[note] = c
        out += [n, q - 2, 63, 2]
    return out + ([0xFE, 0] if loop else [0xFF, 0])


def db(b):
    return "    db " + ",".join(str(x) for x in b)


def main():
    deviations = {}
    out = ["; GENERATED by src/tools/music.py: do not edit by hand.",
           "; per channel: pairs (n, frames); n = 0xFE loops back to the start, 0xFF ends", ""]
    pieces = [("title", TITLE, True, TRANSPOSE["title"])] + \
             [(f"end_{k}", v, False, TRANSPOSE[k]) for k, v in ENDINGS.items()]
    for name, (c2, c3), loop, k in pieces:
        out += [f"mus_{name}: dw mus_{name}_2,mus_{name}_3"]
        for i, txt in ((2, c2), (3, c3)):
            b = channel(txt, loop, deviations, k)
            out += [f"mus_{name}_{i}:"] + [db(b[j:j + 16]) for j in range(0, len(b), 16)]
        out.append("")
    out += ["; ending screen music by ending type (order of TYPES in src/tools/rom.py)",
            "tab_mus_end: dw " + ",".join(f"mus_end_{k}" for k in ENDINGS)]
    dest = ROOT / "src" / "rom" / "generated" / "music.asm"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text("\n".join(out) + "\n")
    print(f"{dest.relative_to(ROOT)}: {len(pieces)} pieces")
    print("tuning (cents):", ", ".join(f"{k} {v:+.0f}" for k, v in
                                       sorted(deviations.items(), key=lambda kv: freq(kv[0]))))


if __name__ == "__main__":
    main()
