#!/usr/bin/env python3
"""Test ROM with the author's portrait in several versions (the current one and reduced ones), to
pick one that uses less space: build/portraits.bin.

Uses the gallery program (src/rom/gallery.asm): Fire 1 (or →) moves forward, Fire 2 (or ←)
moves back. Below each version is shown how much it would cost INSIDE THE GAME: the count is
done on the real bank 1, with its other images, swapping only the portrait.

The files go to build/portraits/generated/ (the game and the gallery are not touched).

Usage:  python3 src/tools/portraits.py      (or: make portraits)
"""
import subprocess
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import art  # noqa: E402
import image_codec  # noqa: E402
import font  # noqa: E402
import tiles  # noqa: E402
from art import B, K, R, W, Y  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent.parent
OUTPUT = ROOT / "build" / "portraits" / "generated"
SEPIA4 = dict(levels=(0, 0.33, 0.75, 1), colors=[K, R, Y, W])
VERSIONS = [  # (name on screen, parameters of art.portrait)
    ("ATUAL", dict(**SEPIA4)),
    ("SÉPIA SEM PONTILHADO", dict(**SEPIA4, dither=False)),
    ("SÉPIA EM 3 TONS", dict(levels=(0, 0.45, 1), colors=[K, R, Y])),
    ("3 TONS COM BRANCO", dict(levels=(0, 0.45, 1), colors=[K, R, W])),
    ("PRETO E BRANCO", dict(levels=(0, 1), colors=[K, W])),
    ("PRETO E BRANCO LISO", dict(levels=(0, 1), colors=[K, W], dither=False)),
    ("MENOR (6 X 8)", dict(**SEPIA4, width=6, height=8, row=1)),
    ("MENOR SEM PONTILHADO", dict(**SEPIA4, width=6, height=8, row=1, dither=False)),
    ("MENOR PRETO E BRANCO", dict(levels=(0, 1), colors=[K, W], width=6, height=8, row=1)),
]


def font_fixed():
    f = {}
    for c, b in sorted(enumerate(font.tiles(), start=1), key=lambda cb: (cb[0] < 0x20, cb[0])):
        f.setdefault(bytes(b), c)
    return f


def main():
    fixed = font_fixed()
    drawings = {f"v{i}": art.portrait(**p).a for i, (_, p) in enumerate(VERSIONS)}
    original_read = tiles.read_image

    def read_image(name):
        return drawings[name] if name in drawings else original_read(name)
    tiles.read_image = read_image

    # 1. how much each version costs in the game: the real bank 1, with the portrait swapped
    bank1 = [n for n, _, b in tiles.IMAGES if b == 1 and n != "autor"]
    cost = {}
    for name in drawings:
        _, output, _ = tiles.build_bank(bank1 + [name], fixed)
        tmap, pcg = output[name]
        raw = [x for b in pcg for x in b[8:]]
        cost[name] = len(image_codec.rle_map(tmap)) + len(image_codec.lzss(raw))

    # 2. the test ROM: the versions alone, split between the two banks
    names = list(drawings)
    half = (len(names) + 1) // 2
    banks = {0: names[:half], 1: names[half:]}
    OUTPUT.mkdir(parents=True, exist_ok=True)
    header = "; GENERATED by src/tools/portraits.py: do not edit by hand."
    font_tiles = font.tiles()
    out = [header]
    for c, b in enumerate(font_tiles, start=1):
        out += [f"; tile 0x{c:02X}"] + tiles.db(b)
    (OUTPUT / "font.asm").write_text("\n".join(out) + "\n")
    result = {}
    for bank, list_ in banks.items():
        patterns, output, _ = tiles.build_bank(list_, fixed)
        result.update({n: (bank, *output[n], patterns) for n in list_})
        out = [header]
        for k in range(tiles.FREE_ROM):
            out += tiles.db(patterns[k] if k < len(patterns) else [0] * 32)
        (OUTPUT / f"bank{bank}.asm").write_text("\n".join(out) + "\n")

    current = cost["v0"]
    table = [header, f"N_IMAGES: equ {len(names)}", "images:"]
    texts = [header]
    data = [header]
    for i, name in enumerate(names):
        bank, tmap, pcg, patterns = result[name]
        title = VERSIONS[i][0]
        m = image_codec.rle_map(tmap)
        z = image_codec.lzss([x for b in pcg for x in b[8:]])
        table += [f"    db 0x{bank << 5:02X},{len(pcg)}", f"    dw im_{name}_m,im_{name}_p,caption_{name}"]
        data += [f"im_{name}_m:"] + tiles.db(m, 24) + [f"im_{name}_p:"] + tiles.db(z, 24)
        diff = cost[name] - current
        lines_ = [(13, title), (14, f"{i + 1}/{len(names)}"),   # the gallery clears 13-17
                  (16, f"NO JOGO: {cost[name]} BYTES"),
                  (17, "(A ATUAL)" if i == 0 else f"({diff:+d} BYTES)")]
        texts += [f"caption_{name}:"]
        for row, txt in lines_:
            texts += [f"    dw MAP+{row}*32+{16 - len(txt) // 2}"] + tiles.db(font.encode(txt) + [0])
        texts += ["    dw 0"]
        print(f"  {title:22s} in the game: {cost[name]:4d} bytes ({diff:+d})")
    table += ["fixed:"]
    for row, txt in ((20, "FIRE 1 >  PRÓXIMA"), (21, "FIRE 2 <  ANTERIOR"), (23, "RETRATOS DO AUTOR")):
        table += [f"    dw MAP+{row}*32+{16 - len(txt) // 2}"] + tiles.db(font.encode(txt) + [0])
    table += ["    dw 0"]
    (OUTPUT / "images.asm").write_text("\n".join(table) + "\n")
    (OUTPUT / "texts.asm").write_text("\n".join(texts) + "\n")
    # the gallery expects these files; here everything goes in the middle area
    (OUTPUT / "img_rest.asm").write_text("\n".join(data) + "\n")
    (OUTPUT / "img_1c00.asm").write_text(header + "\n")
    (OUTPUT / "img_3c00.asm").write_text(header + "\n")

    rom = ROOT / "build" / "portraits.bin"
    rom.parent.mkdir(parents=True, exist_ok=True)
    # assembles a copy of the gallery program in build/portraits/, next to this generated/ (with
    # src/rom/ also on the path, z80asm would pick up the real gallery's generated/)
    for f in ("gallery.asm", "decompress.asm"):
        (OUTPUT.parent / f).write_text((ROOT / "src" / "rom" / f).read_text())
    subprocess.run(["z80asm", "-I", str(OUTPUT.parent), "-o", str(rom),
                    str(OUTPUT.parent / "gallery.asm")], check=True)
    print(f"{rom.relative_to(ROOT)}: {rom.stat().st_size} bytes, {len(names)} versions")


if __name__ == "__main__":
    main()
